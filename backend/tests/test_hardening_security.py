@pytest.mark.asyncio
async def test_security_headers_and_correlation_id_propagation(client: AsyncClient):
    """Verify security headers and correlation ID in HTTP responses."""
    custom_corr_id = "TEST-CORR-UUID-9911"
    resp = await client.get("/health", headers={"X-Correlation-ID": custom_corr_id})

    assert resp.status_code == 200

    # 1. Verify Correlation ID Header
    assert resp.headers.get("X-Correlation-ID") == custom_corr_id

    # 2. Verify Security Headers
    assert resp.headers.get("X-Content-Type-Options") == "nosniff"
    assert resp.headers.get("X-Frame-Options") == "DENY"
    assert resp.headers.get("X-XSS-Protection") == "1; mode=block"
    assert "Strict-Transport-Security" in resp.headers
    assert "Content-Security-Policy" in resp.headers
    assert resp.headers.get("Referrer-Policy") == "strict-origin-when-cross-origin"


