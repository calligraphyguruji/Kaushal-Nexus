@pytest.mark.asyncio
async def test_auth_refresh_token_endpoint(client: AsyncClient):
    """Test POST /api/v1/auth/refresh rotates tokens successfully."""
    unique_email = f"refreshtest.{uuid.uuid4().hex[:6]}@kaushalnexus.gov.in"
    # Register a user
    reg_resp = await client.post(
        "/api/v1/auth/register",
        json={
            "email": unique_email,
            "password": "Password12345!",
            "full_name": "Token Refresh User",
            "role": "MSDE_OFFICER",
        },
    )
    assert reg_resp.status_code == 201

    # Login to get initial refresh token
    login_resp = await client.post(
        "/api/v1/auth/login",
        json={
            "email": unique_email,
            "password": "Password12345!",
        },
    )
    assert login_resp.status_code == 200
    token_data = login_resp.json()
    assert "access_token" in token_data
    assert "refresh_token" in token_data

    # Exchange refresh token
    refresh_resp = await client.post(
        "/api/v1/auth/refresh",
        json={"refresh_token": token_data["refresh_token"]},
    )
    assert refresh_resp.status_code == 200
    new_token_data = refresh_resp.json()
    assert "access_token" in new_token_data
    assert "refresh_token" in new_token_data


