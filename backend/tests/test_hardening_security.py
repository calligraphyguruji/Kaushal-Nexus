# JWT Expiration & Refresh Token Strategy Tests
# ==============================================================================

def test_jwt_access_and_refresh_token_lifecycle():
    """Verify access and refresh tokens enforce distinct token type claims."""
    # 1. Access Token
    access_token = create_access_token(
        subject="user-123",
        role="MSDE_OFFICER",
        expires_delta=timedelta(minutes=30),
    )
    access_payload = decode_access_token(access_token, expected_type="access")
    assert access_payload["sub"] == "user-123"
    assert access_payload["role"] == "MSDE_OFFICER"
    assert access_payload["type"] == "access"

    # 2. Refresh Token
    refresh_token = create_refresh_token(
        subject="user-123",
        role="MSDE_OFFICER",
        expires_delta=timedelta(days=7),
    )
    refresh_payload = decode_access_token(refresh_token, expected_type="refresh")
    assert refresh_payload["sub"] == "user-123"
    assert refresh_payload["type"] == "refresh"

    # 3. Cross-type rejection
    with pytest.raises(Exception):
        # Attempting to use access token as refresh token must fail
        decode_access_token(access_token, expected_type="refresh")


