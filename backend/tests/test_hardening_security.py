@pytest.mark.asyncio
async def test_audit_log_recording_and_query_api(
    client: AsyncClient, auth_headers: dict
):
    """Verify action audit logging and GET /api/v1/audit/logs endpoint."""
    async with AsyncSessionLocal() as session:
        # Record direct audit event
        await audit_service.log_action(
            db=session,
            action="ADMIN_CONFIG_UPDATE",
            resource_type="SYSTEM",
            resource_id="SECURITY_POLICY_2026",
            actor_email="admin@kaushalnexus.gov.in",
            status="SUCCESS",
            details={"setting": "RATE_LIMIT_AUTH", "new_value": 15},
        )

    # Query audit logs via API
    resp = await client.get(
        "/api/v1/audit/logs",
        params={"action": "ADMIN_CONFIG_UPDATE"},
        headers=auth_headers,
    )
    assert resp.status_code == 200
    data = resp.json()
    assert data["total"] >= 1
    assert any(item["action"] == "ADMIN_CONFIG_UPDATE" for item in data["items"])
