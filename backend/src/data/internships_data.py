def score_internship_match(
    internship: Dict[str, Any],
    learner_domain: str = "fullstack",
    readiness_score: int = 65,
    active_gaps: Optional[List[str]] = None,
) -> Dict[str, Any]:
    """Computes explainable dynamic match score between candidate and internship."""
    active_gaps = [g.lower() for g in (active_gaps or [])]
    req_skills = internship.get("required_skills", [])
    pref_skills = internship.get("preferred_skills", [])

    matched = []
    missing = []

    for s in req_skills:
        s_lower = s.lower()
        if any(g in s_lower or s_lower in g for g in active_gaps):
            missing.append(s)
        else:
            matched.append(s)

    for s in pref_skills:
        s_lower = s.lower()
        if not any(g in s_lower or s_lower in g for g in active_gaps):
            matched.append(s)

    skill_ratio = (len(matched) / max(len(req_skills), 1)) if req_skills else 0.8
    domain_bonus = 15 if learner_domain == internship.get("interest") else 0
    readiness_delta = readiness_score - internship.get("min_readiness_score", 50)
    readiness_bonus = min(15, max(-10, int(readiness_delta * 0.3)))

    score = min(98, max(45, int((skill_ratio * 70) + domain_bonus + readiness_bonus)))

    tier = "Direct Competency Match" if score >= 80 else ("High Potential Match" if score >= 65 else "Moderate Match")
    return {
        "match_score": score,
        "matched_skills": matched,
        "missing_skills": missing,
        "match_tier": tier,
        "is_primary_interest": learner_domain == internship.get("interest"),
    }
