/**
 * Calculates candidate dynamic match score against a given internship.
 * Takes the learner's tested skills, active gaps, and readiness score.
 */
export function calculateInternshipMatch(internship, learnerProfile = {}, activeGaps = []) {
  if (!internship) return { matchScore: 0, matchedSkills: [], missingSkills: [] };

  const testedDomain = learnerProfile.target_domain || "fullstack";
  const candidateReadiness = learnerProfile.employment_readiness_score || 65;

  // Extract learner's mastered skills and gap skills
  const gapSkillNames = (activeGaps || []).map((g) => (g.skill_name || g.name || "").toLowerCase());
  
  // Also check if candidate has evaluated skills list
  const assessedMasteries = learnerProfile.masteries || [];
  const masteredMap = {};
  assessedMasteries.forEach((m) => {
    masteredMap[(m.skill_name || "").toLowerCase()] = m.is_mastered || m.posterior_mastery >= 0.7;
  });

  const reqSkills = internship.requiredSkills || [];
  const prefSkills = internship.preferredSkills || [];

  let matchedReqCount = 0;
  const matchedSkills = [];
  const missingSkills = [];

  reqSkills.forEach((skill) => {
    const sLower = skill.toLowerCase();
    // If not recorded as an active deficit/gap, and either tested domain aligns or candidate has good readiness
    const isGap = gapSkillNames.some((g) => g.includes(sLower) || sLower.includes(g));
    const isMastered = masteredMap[sLower];

    if (!isGap && (isMastered !== false)) {
      matchedReqCount += 1;
      matchedSkills.push(skill);
    } else {
      missingSkills.push(skill);
    }
  });

  prefSkills.forEach((skill) => {
    const sLower = skill.toLowerCase();
    const isGap = gapSkillNames.some((g) => g.includes(sLower) || sLower.includes(g));
    if (!isGap) {
      matchedSkills.push(skill);
    }
  });

  // Base skill match percentage
  const skillRatio = reqSkills.length > 0 ? (matchedReqCount / reqSkills.length) : 0.8;
  
  // Domain relevance weight: If learner's target interest matches internship interest: 15% boost
  const domainBonus = testedDomain === internship.interest ? 15 : (
    (testedDomain === "fullstack" && internship.interest === "python") ||
    (testedDomain === "python" && internship.interest === "aiml") ||
    (testedDomain === "data" && internship.interest === "digital")
  ) ? 8 : 0;

  // Readiness factor
  const minReadiness = internship.minReadinessScore || 50;
  const readinessDelta = candidateReadiness - minReadiness;
  const readinessBonus = Math.min(15, Math.max(-10, Math.round(readinessDelta * 0.3)));

  // Compute final match score clamped between 45 and 98
  let rawScore = Math.round((skillRatio * 70) + domainBonus + readinessBonus);
  if (rawScore > 98) rawScore = 98;
  if (rawScore < 45) rawScore = 45;

  let tier = "Moderate Match";
  let tierTone = "amber";
  if (rawScore >= 80) {
    tier = "Direct Competency Match";
    tierTone = "emerald";
  } else if (rawScore >= 65) {
    tier = "High Potential Match";
    tierTone = "sky";
  }

  return {
    matchScore: rawScore,
    matchedSkills,
    missingSkills,
    tier,
    tierTone,
    isPrimaryInterest: testedDomain === internship.interest,
    openings: internship.openings,
  };
}

/**
 * Filter and sort internships dynamically
 */
export function queryInternships({
  interest = "all",
  search = "",
  workMode = "all",
  minStipend = 0,
  sortBy = "match", // 'match' | 'stipend' | 'openings'
  learnerProfile = {},
  activeGaps = [],
} = {}) {
  let list = [...ALL_INTERNSHIPS];

  // Filter by interest track
  if (interest && interest !== "all") {
    list = list.filter((i) => i.interest === interest);
  }

  // Filter by work mode
  if (workMode && workMode !== "all") {
    list = list.filter((i) => i.workMode.toLowerCase() === workMode.toLowerCase());
  }

  // Filter by min stipend
  if (minStipend > 0) {
    list = list.filter((i) => i.stipendInr >= minStipend);
  }

  // Filter by search keyword
  if (search && search.trim()) {
    const q = search.trim().toLowerCase();
    list = list.filter(
      (i) =>
        i.title.toLowerCase().includes(q) ||
        i.company.toLowerCase().includes(q) ||
        i.location.toLowerCase().includes(q) ||
        (i.requiredSkills && i.requiredSkills.some((s) => s.toLowerCase().includes(q))) ||
        (i.preferredSkills && i.preferredSkills.some((s) => s.toLowerCase().includes(q)))
    );
  }

  // Attach dynamic match score to each internship
  const enriched = list.map((item) => {
    const matchData = calculateInternshipMatch(item, learnerProfile, activeGaps);
    return {
      ...item,
      ...matchData,
    };
  });

  // Sort
  if (sortBy === "stipend") {
    enriched.sort((a, b) => b.stipendInr - a.stipendInr);
  } else if (sortBy === "openings") {
    enriched.sort((a, b) => b.openings - a.openings);
  } else {
    // Default: Sort by matchScore descending, with primary interest prioritized
    enriched.sort((a, b) => {
      if (b.isPrimaryInterest !== a.isPrimaryInterest) {
        return b.isPrimaryInterest ? 1 : -1;
      }
      return b.matchScore - a.matchScore;
    });
  }

  return enriched;
}
